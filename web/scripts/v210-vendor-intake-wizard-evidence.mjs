import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
const { chromium } = createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE ?? "playwright");
const base = process.env.PAGE_URL ?? "http://127.0.0.1:4173";
const output = path.resolve(process.env.UI_EVIDENCE_DIR ?? "../docs/evidence/2026-11-21-v210-vendor-intake");
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_BROWSER_PATH ? { executablePath: process.env.PLAYWRIGHT_BROWSER_PATH } : {}) });
const results = [];
try {
  for (const width of [1440, 1280, 1024, 768, 390]) {
    const page = await browser.newPage({ viewport: { width, height: 900 }, reducedMotion: "reduce" });
    await page.goto(`${base}/#/vendors`);
    await page.getByRole("button", { name: "Add vendor" }).click();
    await page.getByLabel("Legal name").fill("Sample Atlas");
    await page.getByRole("button", { name: "Check existing vendors" }).click();
    const match = page.getByRole("link", { name: "Sample Atlas Ltd · Hosting (opens in new tab)" });
    assert.equal(await match.getAttribute("href"), "#/vendors/sample-vendor");
    assert.equal(await match.getAttribute("target"), "_blank");
    await page.screenshot({ path: path.join(output, `matching-vendor-${width}.png`), fullPage: true });
    await page.getByLabel("Legal name").fill("Sample Vendor Limited");
    await page.getByRole("button", { name: "Continue", exact: true }).click();
    await page.getByRole("heading", { name: "Service details" }).waitFor();
    assert.equal(await page.getByRole("heading", { name: "Service details" }).evaluate((node) => document.activeElement === node), true);
    await page.getByLabel("Service", { exact: true }).fill("Payment processing");
    await page.getByLabel("Criticality").selectOption("IMPORTANT");
    await page.getByLabel("Privacy role").selectOption("PROCESSOR");
    await page.screenshot({ path: path.join(output, `service-${width}.png`), fullPage: true });
    await page.getByRole("button", { name: "Review relationship" }).click();
    await page.getByRole("heading", { name: "Review relationship" }).waitFor();
    assert.equal(await page.getByRole("heading", { name: "Review relationship" }).evaluate((node) => document.activeElement === node), true);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: path.join(output, `review-${width}.png`), fullPage: true });
    await page.getByRole("button", { name: "Edit vendor details" }).click();
    assert.equal(await page.getByLabel("Legal name").inputValue(), "Sample Vendor Limited");
    await page.getByRole("button", { name: "Continue", exact: true }).click();
    await page.getByRole("button", { name: "Review relationship" }).click();
    await page.getByRole("button", { name: "Back", exact: true }).click();
    assert.equal(await page.getByLabel("Service", { exact: true }).inputValue(), "Payment processing");
    await page.getByRole("button", { name: "Review relationship" }).click();
    await page.getByRole("button", { name: "Create relationship" }).click();
    await page.getByRole("heading", { name: "Relationship status unknown" }).waitFor();
    assert.equal(await page.getByText("Payment processing", { exact: true }).count(), 1);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: path.join(output, `unknown-${width}.png`), fullPage: true });
    await page.getByRole("button", { name: "View vendors" }).click();
    await page.getByRole("heading", { name: "Vendor relationships" }).waitFor();
    assert.equal(await page.getByRole("heading", { name: "Relationship status unknown" }).count(), 1);
    assert.equal(await page.getByText("Payment processing", { exact: true }).count(), 1);
    assert.equal(await page.getByRole("button", { name: "Add vendor" }).count(), 0);
    await page.screenshot({ path: path.join(output, `recovery-${width}.png`), fullPage: true });
    await page.getByRole("button", { name: "Dismiss details" }).click();
    assert.equal(await page.getByRole("button", { name: "Add vendor" }).count(), 1);
    results.push({ width, overflow: false, focus: true, matchLink: true, editRetainsValue: true, backRetainsValue: true, uncertainDetailsRetained: true }); await page.close();
  }
  await writeFile(path.join(output, "results.json"), JSON.stringify({ results }, null, 2));
  console.log(`Vendor intake evidence passed at ${results.length} widths.`);
} finally { await browser.close(); }
